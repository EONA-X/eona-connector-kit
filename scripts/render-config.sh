#!/usr/bin/env bash
#
# Render compose/config/<service>/config.properties from .env.
#
# Why a file and not environment variables: EDC maps an environment variable to
# a config key by lowercasing it and turning "_" into ".", so a key with a
# hyphen in it — edc.iam.trusted-issuer.<alias>.id,
# edc.migration.barrier.expected-modules,
# edc.vault.hashicorp.token.scheduled-renew-enabled — can only be expressed by
# putting a literal hyphen in the variable's NAME. Kubernetes accepts such
# names and so does compose's `environment:` map, but a POSIX shell, an
# env_file, and most tooling do not. The properties file is the portable
# channel, so every hyphenated key goes here.
#
# Note the precedence, which is the opposite of what the file's name suggests:
# EDC merges fileConfig < environment < system properties, so anything
# compose.yaml sets as an environment variable OVERRIDES what is written here.
# Nothing in this file is also set in compose.yaml; keep it that way.
#
# Anything you add to compose/config/<service>/extra.properties is appended
# verbatim and is never overwritten by this script. Because that content is
# copied INTO config.properties, the rendered config.properties files are
# gitignored too (compose/.gitignore) — otherwise a credential you put in the
# protected file would be committed from the generated one. They are build
# artefacts: this script regenerates them, and --check verifies them.
#
# Usage: render-config.sh [--check]
#   --check   render to a temporary file and report whether the config.properties
#             files on disk are up to date, without writing anything
set -euo pipefail
. "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

CHECK_ONLY=0
[ "${1:-}" = "--check" ] && CHECK_ONLY=1

load_env

: "${MIGRATION_BARRIER_EXPECTED_MODULES:=Control Plane Database Migration,Data Plane Database Migration,Identity Hub Database Migration}"
: "${MIGRATION_BARRIER_TIMEOUT_SECONDS:=300}"
: "${DB_POOL_MAX_TOTAL:=5}"
: "${VAULT_TOKEN_SCHEDULED_RENEW_ENABLED:=false}"
: "${VAULT_TOKEN_RENEW_BUFFER:=30}"
: "${TRUSTED_ISSUERS:=}"
: "${NEGOTIATION_STATE_MACHINE_WAIT_MILLIS:=2000}"
: "${TRANSFER_STATE_MACHINE_WAIT_MILLIS:=2000}"
: "${POLICY_MONITOR_STATE_MACHINE_WAIT_MILLIS:=5000}"
: "${DATAPLANE_STATE_MACHINE_WAIT_MILLIS:=5000}"
: "${DATAPLANE_CONSUMER_GATEWAY_THREAD_POOL:=5}"

header() {
  cat <<EOF
# ---------------------------------------------------------------------------
# GENERATED by scripts/render-config.sh from compose/.env — do not edit.
# Add your own settings to compose/config/$1/extra.properties instead;
# they are appended below, verbatim, and never overwritten.
# ---------------------------------------------------------------------------

EOF
}

# Every runtime shares the same Vault and the same database, so these are common.
common_block() {
  cat <<EOF
# --- Vault -----------------------------------------------------------------
# Hyphenated keys. A root token (the bundled dev-mode default) has no TTL to
# renew, so scheduled renewal must stay off for the evaluation stack. Turn it on
# when you give the connector a scoped, renewable token.
edc.vault.hashicorp.token.scheduled-renew-enabled=${VAULT_TOKEN_SCHEDULED_RENEW_ENABLED}
edc.vault.hashicorp.token.renew-buffer=${VAULT_TOKEN_RENEW_BUFFER}

# --- Database pool ---------------------------------------------------------
# Hyphenated key. Size it for your database's connection budget: the three
# runtimes each open their own pool against the same instance.
edc.datasource.default.pool.connections.max-total=${DB_POOL_MAX_TOTAL}
EOF

  if [ -n "$MIGRATION_BARRIER_EXPECTED_MODULES" ]; then
    cat <<EOF

# --- Migration barrier -----------------------------------------------------
# Hyphenated keys, and the one genuinely cross-service setting in the kit.
#
# All three runtimes migrate the same database and each carries the shared
# migration set, which reshapes edc_lease destructively. Without this list, the
# first runtime to reach the shared set applies it and the siblings' own 0.14
# baselines then fail on a foreign key into a table whose primary key changed
# arity. With it, each runtime applies its own migrations, records its signal
# key, and waits for the others before touching the shared set.
#
# The values are the migration modules' names, verbatim. Clear this setting ONLY
# if you give each runtime its own database — and note that giving the
# data-plane a database of its own silently breaks the consumer data gateway,
# which reads EDR rows the control-plane writes.
edc.migration.barrier.expected-modules=${MIGRATION_BARRIER_EXPECTED_MODULES}
edc.migration.barrier.timeout-seconds=${MIGRATION_BARRIER_TIMEOUT_SECONDS}
EOF
  else
    cat <<EOF

# --- Migration barrier -----------------------------------------------------
# Disabled: MIGRATION_BARRIER_EXPECTED_MODULES is empty in .env. That is only
# safe when this runtime is the sole migration contributor on its database.
EOF
  fi
}

trusted_issuer_block() {
  cat <<EOF

# --- Trusted credential issuers --------------------------------------------
# Hyphenated keys. Every issuer whose verifiable credentials this connector will
# accept, one alias per issuer. The dataspace authority belongs here; so does
# every peer participant that issues a credential you must verify.
#
# A malformed entry — properties without a matching .id — fails the entire boot.
# There is no per-issuer degradation.
EOF
  if [ -z "$TRUSTED_ISSUERS" ]; then
    printf '%s\n' "# (none configured — set TRUSTED_ISSUERS in .env)"
    return
  fi
  local entry alias did
  local -a entries
  # Space- or comma-separated alias=did pairs. read -a splits on whitespace
  # without pathname expansion, which an unquoted $(...) loop would apply.
  read -ra entries <<< "$(printf '%s' "$TRUSTED_ISSUERS" | tr ',' ' ')"
  for entry in ${entries[@]+"${entries[@]}"}; do
    case "$entry" in
      *=*) ;;
      *) die "TRUSTED_ISSUERS entry '$entry' is not of the form alias=did" ;;
    esac
    alias="${entry%%=*}"
    did="${entry#*=}"
    if [ -z "$alias" ] || [ -z "$did" ]; then
      die "TRUSTED_ISSUERS entry '$entry' has an empty alias or DID"
    fi
    printf 'edc.iam.trusted-issuer.%s.id=%s\n' "$alias" "$did"
  done
}

management_auth_block() {
  cat <<'EOF'

# --- Management API authentication -----------------------------------------
EOF
  if [ "$MANAGEMENT_API_AUTH_ENABLED" = "true" ]; then
    cat <<EOF
# Static bearer token. The alias is resolved from Vault at boot, so the key
# itself never appears in a config file or an environment variable. Callers send
# it as the "x-api-key" header.
#
# This is stricter than the reference Kubernetes deployment, which serves the
# management API unauthenticated and relies on it not being routed publicly.
# Set MANAGEMENT_API_AUTH_ENABLED=false in .env to match that posture — but then
# never publish port 8181 anywhere but localhost.
web.http.management.auth.type=tokenbased
web.http.management.auth.key.alias=${MANAGEMENT_API_KEY_ALIAS}
EOF
  else
    cat <<'EOF'
# DISABLED (MANAGEMENT_API_AUTH_ENABLED=false in .env). The management API is
# served with no authentication at all: anyone who can reach port 8181 can
# create assets, policies and contract definitions. Keep it bound to localhost.
EOF
  fi
}

append_extra() {
  # Declared one per line on purpose: bash expands every assignment word on a
  # `local` line BEFORE performing any of the assignments, so a single-line
  # `local svc="$1" extra=".../${svc}/..."` would expand ${svc} to whatever it
  # held in the CALLER's scope, not to $1 (shellcheck SC2318). That happens to
  # work here only because the caller's loop variable is also named svc.
  local svc="$1"
  local out="$2"
  local extra="${CONFIG_DIR}/${svc}/extra.properties"
  if [ -f "$extra" ]; then
    {
      printf '\n# --- appended from config/%s/extra.properties -----------------\n' "$svc"
      cat "$extra"
    } >> "$out"
  fi
}

render_control_plane() {
  local out="$1"
  { header control-plane; common_block; trusted_issuer_block; management_auth_block
    cat <<EOF

# --- State machine tuning --------------------------------------------------
# Hyphenated keys. How long each state machine waits between iterations when it
# has nothing to do. Lower means snappier negotiations and more database load.
edc.negotiation.state-machine.iteration-wait-millis=${NEGOTIATION_STATE_MACHINE_WAIT_MILLIS}
edc.transfer.state-machine.iteration-wait-millis=${TRANSFER_STATE_MACHINE_WAIT_MILLIS}
edc.policy.monitor.state-machine.iteration-wait-millis=${POLICY_MONITOR_STATE_MACHINE_WAIT_MILLIS}
EOF
  } > "$out"
  append_extra control-plane "$out"
}

render_data_plane() {
  local out="$1"
  { header data-plane; common_block
    cat <<EOF

# --- State machine and gateway tuning --------------------------------------
edc.dataplane.state-machine.iteration-wait-millis=${DATAPLANE_STATE_MACHINE_WAIT_MILLIS}
# Thread pool for the consumer data gateway on /api/data.
edc.dpf.dataplane.consumer.gateway.thread.pool=${DATAPLANE_CONSUMER_GATEWAY_THREAD_POOL}
EOF
  } > "$out"
  append_extra data-plane "$out"
}

render_identity_hub() {
  local out="$1"
  { header identity-hub; common_block; } > "$out"
  append_extra identity-hub "$out"
}

status=0
for svc in control-plane data-plane identity-hub; do
  target="${CONFIG_DIR}/${svc}/config.properties"
  tmp="$(mktemp)"
  case "$svc" in
    control-plane) render_control_plane "$tmp" ;;
    data-plane)    render_data_plane    "$tmp" ;;
    identity-hub)  render_identity_hub  "$tmp" ;;
  esac

  if [ "$CHECK_ONLY" -eq 1 ]; then
    if [ -f "$target" ] && cmp -s "$tmp" "$target"; then
      ok "config/${svc}/config.properties is up to date"
    else
      warn "config/${svc}/config.properties differs from what .env would render"
      status=1
    fi
    rm -f "$tmp"
  else
    mkdir -p "$(dirname "$target")"
    mv "$tmp" "$target"
    chmod 0644 "$target"
    ok "rendered config/${svc}/config.properties"
  fi
done

exit "$status"
